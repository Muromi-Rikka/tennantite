export function Demo({ name }: { name: string }) {
  const key = `${name}Demo`;
  const Component = registry[key];
  if (!Component) {
    return (
      <p className="font-mc mc-text text-mc-red">
        缺少示例：
        {name}
      </p>
    );
  }
  const spec = LIVE_SPECS[key];
  return spec ? <LiveDemo Component={Component} spec={spec} /> : <Component />;
}

